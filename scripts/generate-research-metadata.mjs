import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, extname, basename, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const contentDir = resolve(root, "content/research");

function storyLiteral(source, file) {
  const sf = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
  for (const statement of sf.statements) {
    if (!ts.isVariableStatement(statement)) continue;
    for (const declaration of statement.declarationList.declarations) {
      if (!ts.isIdentifier(declaration.name) || declaration.name.text !== "story" || !declaration.initializer) continue;
      let node = declaration.initializer;
      if (ts.isSatisfiesExpression(node)) node = node.expression;
      if (!ts.isObjectLiteralExpression(node)) throw new Error(`${file}: story must be an object literal`);
      return source.slice(node.getStart(sf), node.getEnd());
    }
  }
  throw new Error(`${file}: missing exported story record`);
}

const files = (await readdir(contentDir))
  .filter((file) => extname(file) === ".tsx")
  .sort();

if (!files.length) throw new Error("No research article files found.");

const records = [];
for (const file of files) records.push(storyLiteral(await readFile(resolve(contentDir, file), "utf8"), file));

const metadataOutput = `// Generated by scripts/generate-research-metadata.mjs. Do not edit by hand.
import type { ResearchStory } from "./research-article";

export const researchStories: ResearchStory[] = [
${records.map((record) => `  ${record},`).join("\n")}
].sort((a, b) => Date.parse(b.datePublished) - Date.parse(a.datePublished));

export const featuredResearchStory =
  researchStories.find((story) => story.featured) ?? researchStories[0];

export function getResearchStory(slug: string) {
  return researchStories.find((story) => story.slug === slug);
}
export function getResearchStoriesForState(stateCode: string) {
  return researchStories.filter((story) => story.stateCodes.includes(stateCode));
}
export function getResearchStoriesForCompany(company: string) {
  const normalized = company.trim().toLowerCase();
  return researchStories.filter((story) =>
    story.companies.some((item) => item.toLowerCase() === normalized),
  );
}
export function getResearchStoriesForAuthor(authorSlug: string) {
  return researchStories.filter((story) => story.authorSlug === authorSlug);
}
export function getLatestResearchStories(limit = 3) {
  return researchStories.slice(0, limit);
}
export function getLatestResearchModifiedDate() {
  return researchStories.reduce(
    (latest, story) => story.dateModified > latest ? story.dateModified : latest,
    "1970-01-01",
  );
}
`;

const imports = files.map((file, index) =>
  `import { article as article${index} } from "./${basename(file, ".tsx")}";`
).join("\n");
const articleNames = files.map((_, index) => `article${index}`).join(",\n  ");

const registryOutput = `// Generated by scripts/generate-research-metadata.mjs. Do not edit by hand.
${imports}

const discoveredArticles = [
  ${articleNames},
];

export const researchArticles = Object.fromEntries(
  discoveredArticles.map((article) => [article.story.slug, article]),
);

export function getResearchArticle(slug: string) {
  return researchArticles[slug];
}

export function getResearchContent(slug: string) {
  const article = getResearchArticle(slug);
  return article ? { Body: article.Body, ...article.config } : undefined;
}
`;

await Promise.all([
  writeFile(resolve(root, "lib/research-stories.ts"), metadataOutput),
  writeFile(resolve(contentDir, "index.ts"), registryOutput),
]);
console.log("Generated research registries from " + files.length + " discovered article files.");
